#!/usr/bin/env node
// Compiles data/exam.json and every existing data/modules/*.json into data/bundle.js
// (loaded by index.html, so the page works when opened straight from disk) and writes
// a Markdown answer key for each module into docs/. Run: node scripts/build.mjs
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { basename, dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const dataDir = join(root, 'data');
const docsDir = join(root, 'docs');
const LETTERS = ['A', 'B', 'C', 'D'];
const DIFFICULTIES = ['EASY', 'MEDIUM', 'HARD'];

const readJson = (path) => JSON.parse(readFileSync(path, 'utf8'));
const exam = readJson(join(dataDir, 'exam.json'));
const errors = [];
const content = {};

for (const entry of exam.modules) {
  const path = join(dataDir, entry.file);
  if (!existsSync(path)) continue;
  const mod = readJson(path);
  validate(entry, mod);
  content[entry.id] = mod;
}

if (errors.length) {
  console.error(`Build failed with ${errors.length} problem(s):`);
  errors.forEach((e) => console.error(`  - ${e}`));
  process.exit(1);
}

const bundle = { ...exam, builtAt: new Date().toISOString(), content };
writeFileSync(
  join(dataDir, 'bundle.js'),
  `// Generated by scripts/build.mjs. Edit the JSON files in data/, then run: node scripts/build.mjs\n` +
    `window.SAT_EXAM = ${JSON.stringify(bundle, null, 2)};\n`,
);

mkdirSync(docsDir, { recursive: true });
for (const entry of exam.modules) {
  const mod = content[entry.id];
  if (!mod) continue;
  const out = join(docsDir, `${basename(entry.file, '.json')}-answer-key.md`);
  writeFileSync(out, moduleMarkdown(entry, mod));
}

for (const entry of exam.modules) {
  const mod = content[entry.id];
  if (!mod) {
    console.log(`Module ${entry.sequence} (${entry.id}): not generated yet`);
    continue;
  }
  const qs = mod.questions;
  const count = (key, value) => qs.filter((q) => q[key] === value).length;
  const planned = qs.reduce((s, q) => s + q.targetSeconds, 0);
  const letters = LETTERS.map((L) => `${L}:${count('answer', L)}`).join(' ');
  const levels = DIFFICULTIES.map((d) => `${d}:${count('difficulty', d)}`).join(' ');
  console.log(
    `Module ${entry.sequence} (${entry.id}): ${qs.length} questions | ${levels} | ${letters} | ` +
      `target ${mmss(planned)} of ${entry.minutes}:00`,
  );
}
console.log('Wrote data/bundle.js and docs/*-answer-key.md');

function validate(entry, mod) {
  const where = `${entry.file}`;
  const fail = (msg) => errors.push(`${where}: ${msg}`);
  if (mod.id !== entry.id) fail(`id "${mod.id}" does not match exam.json id "${entry.id}"`);
  if (!Array.isArray(mod.questions)) return fail('questions must be an array');
  if (mod.questions.length !== entry.questions) {
    fail(`has ${mod.questions.length} questions; exam.json expects ${entry.questions}`);
  }
  const ids = new Set();
  mod.questions.forEach((q, i) => {
    const at = `question ${i + 1} (${q.id ?? 'no id'})`;
    if (ids.has(q.id)) fail(`${at}: duplicate id`);
    ids.add(q.id);
    if (q.number !== i + 1) fail(`${at}: number should be ${i + 1}`);
    for (const key of ['domain', 'skill', 'stem']) if (!q[key]) fail(`${at}: missing ${key}`);
    if (!DIFFICULTIES.includes(q.difficulty)) fail(`${at}: difficulty must be one of ${DIFFICULTIES.join(', ')}`);
    if (!(q.targetSeconds > 0)) fail(`${at}: targetSeconds must be a positive number`);
    if (q.type === 'mcq') {
      if (!LETTERS.every((L) => typeof q.choices?.[L] === 'string')) fail(`${at}: needs choices A-D`);
      if (!LETTERS.includes(q.answer)) fail(`${at}: answer must be A, B, C, or D`);
      if (!q.explanation) fail(`${at}: missing explanation`);
      const wrong = LETTERS.filter((L) => L !== q.answer);
      if (!wrong.every((L) => q.distractors?.[L])) fail(`${at}: needs a distractor explanation for ${wrong.join(', ')}`);
      if (q.distractors?.[q.answer]) fail(`${at}: the correct answer should not have a distractor explanation`);
    } else if (q.type === 'spr') {
      if (!Array.isArray(q.answer) || !q.answer.length) fail(`${at}: spr answer must be a non-empty array`);
      if (!Array.isArray(q.solution) || !q.solution.length) fail(`${at}: spr questions need solution steps`);
    } else {
      fail(`${at}: type must be "mcq" or "spr"`);
    }
  });
}

function mmss(seconds) {
  const s = Math.round(seconds);
  return `${Math.floor(s / 60)}:${String(s % 60).padStart(2, '0')}`;
}

function inlineMd(html) {
  return html
    .replace(/<u>(.*?)<\/u>/g, '<ins>$1</ins>')
    .replace(/<em>(.*?)<\/em>/g, '*$1*')
    .replace(/<strong>(.*?)<\/strong>/g, '**$1**')
    .replace(/<ul>\s*<li>/g, '- ')
    .replace(/<\/li>\s*<li>/g, '\n- ')
    .replace(/<\/li>\s*<\/ul>/g, '')
    .replace(/<br\s*\/?>/g, '  \n')
    .replace(/<sup>(.*?)<\/sup>/g, '^$1')
    .replace(/<\/?(span|div|p)[^>]*>/g, '');
}

function quote(text) {
  return text.split('\n').map((line) => `> ${line}`).join('\n');
}

function figureMd(fig) {
  if (!fig) return '';
  if (fig.type === 'table') {
    const head = `| ${fig.columns.join(' | ')} |\n| ${fig.columns.map(() => '---').join(' | ')} |`;
    const body = fig.rows.map((r) => `| ${r.join(' | ')} |`).join('\n');
    return `**${fig.title}**\n\n${head}\n${body}\n${fig.note ? `\n*${fig.note}*\n` : ''}\n`;
  }
  if (fig.type === 'bar') {
    const cols = ['', ...fig.series.map((s) => s.name)];
    const head = `| ${cols.join(' | ')} |\n| ${cols.map(() => '---').join(' | ')} |`;
    const body = fig.categories.map((c, i) => `| ${c} | ${fig.series.map((s) => s.values[i]).join(' | ')} |`).join('\n');
    return `**${fig.title}** (bar graph; ${fig.yLabel})\n\n${head}\n${body}\n\n`;
  }
  return '';
}

function moduleMarkdown(entry, mod) {
  const qs = mod.questions;
  const lines = [];
  lines.push(`# ${mod.title}`);
  lines.push('');
  lines.push(`${exam.title}, Form ${exam.form} (${exam.edition}). ${entry.minutes} minutes, ${qs.length} questions.`);
  if (mod.difficultyProfile) lines.push(`\n${mod.difficultyProfile}`);
  lines.push('\n## Answer key\n');
  const isMcq = (q) => q.type === 'mcq';
  lines.push('| Q | Domain | Skill | Difficulty | Answer | Target time |');
  lines.push('|---|---|---|---|---|---|');
  qs.forEach((q) => {
    const ans = isMcq(q) ? q.answer : q.answer.join(' or ');
    lines.push(`| ${q.number} | ${q.domain} | ${q.skill} | [${q.difficulty}] | ${ans} | ${q.targetSeconds} s |`);
  });

  lines.push('\n## Pacing checkpoints\n');
  lines.push('| Checkpoint | Target time spent | Clock should show |');
  lines.push('|---|---|---|');
  let cumulative = 0;
  let i = 0;
  [1, 2, 3, 4].map((k) => Math.ceil((qs.length * k) / 4)).forEach((mark) => {
    for (; i < mark; i++) cumulative += qs[i].targetSeconds;
    lines.push(`| After question ${mark} | ${mmss(cumulative)} | ${mmss(entry.minutes * 60 - cumulative)} |`);
  });

  lines.push('\n## Questions and explanations');
  qs.forEach((q) => {
    lines.push(`\n### Question ${q.number} [${q.difficulty}]\n`);
    lines.push(`**${q.domain} / ${q.skill}**. ⏱ Target: ${q.targetSeconds} seconds\n`);
    const stim = [];
    if (q.intro) stim.push(q.intro);
    (q.passages || []).forEach((p) => stim.push(`${p.label ? `**${p.label}**\n` : ''}${inlineMd(p.html)}`));
    const fig = figureMd(q.figure);
    if (fig) lines.push(fig);
    if (stim.length) lines.push(`${quote(stim.join('\n\n'))}\n`);
    lines.push(`**${inlineMd(q.stem)}**\n`);
    if (isMcq(q)) {
      LETTERS.forEach((L) => lines.push(`- ${L}) ${inlineMd(q.choices[L])}`));
      lines.push(`\n**Correct answer: ${q.answer}**\n`);
      lines.push(`**Key explanation.** ${inlineMd(q.explanation)}\n`);
      lines.push('**Distractor explanations.**\n');
      LETTERS.filter((L) => L !== q.answer).forEach((L) => lines.push(`- **${L}:** ${inlineMd(q.distractors[L])}`));
    } else {
      lines.push('Enter your answer.\n');
      lines.push(`**Correct answer: ${q.answer.join(' or ')}**\n`);
      lines.push('**Step-by-step solution.**\n');
      q.solution.forEach((step, n) => lines.push(`${n + 1}. ${inlineMd(step)}`));
    }
    if (q.tip) lines.push(`\n**Tip.** ${inlineMd(q.tip)}`);
  });
  lines.push('');
  return lines.join('\n');
}
